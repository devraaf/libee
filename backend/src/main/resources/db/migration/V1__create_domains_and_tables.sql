-- Domains
-- ---------------------------------------------------------------
-- ISBN sem hífens: ISBN-10 (9 dígitos + dígito verificador, que pode ser X) ou ISBN-13 (13 dígitos)
CREATE DOMAIN dom_isbn AS varchar(13)
    CHECK (VALUE ~ '^([0-9]{9}[0-9X]|[0-9]{13})$');

-- Telefone brasileiro, somente dígitos, com DDD e sem código do país: fixo (10 dígitos, começando em 2 a 5) ou celular (11 dígitos, começando em 9)
CREATE DOMAIN dom_phone AS varchar(11)
    CHECK (VALUE ~ '^[1-9]{2}(9[0-9]{8}|[2-5][0-9]{7})$');

-- Tipo vínculo do usuário conforme enum
CREATE DOMAIN dom_affiliation_type AS varchar(20)
    CHECK (VALUE IN ('STUDENT', 'EMPLOYEE', 'PROFESSOR'));

-- Tipo perfil do usuário conforme enum
CREATE DOMAIN dom_profile AS varchar(20)
    CHECK (VALUE IN ('READER', 'LIBRARIAN', 'ADMINISTRATOR'));

-- Status do exemplar conforme enum
CREATE DOMAIN dom_copy_status AS varchar(20)
    CHECK (VALUE IN ('AVAILABLE', 'ON_LOAN'));

-- ---------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------
CREATE TABLE courses (
     id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     name varchar(150) NOT NULL
);

CREATE TABLE users (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(255) NOT NULL,
    email            varchar(255) NOT NULL UNIQUE,
    password_hash         varchar(255) NOT NULL,
    phone            dom_phone,
    affiliation_type dom_affiliation_type NOT NULL,
    profile          dom_profile NOT NULL
);

-- Especialização de usuario: apenas para tipo_vinculo = 'ALUNO'
CREATE TABLE students (
    user_id   integer PRIMARY KEY REFERENCES users (id),
    course_id integer NOT NULL REFERENCES courses (id)
);

CREATE TABLE authors (
     id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     name varchar(255) NOT NULL
);

CREATE TABLE categories (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
);

CREATE TABLE books (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn              dom_isbn NOT NULL UNIQUE,
    title             varchar(255) NOT NULL,
    publisher         varchar(150),
    publication_place varchar(100),
    edition           varchar(50),
    cover_image_url   varchar(500),
    publication_date  date,
    page_count        integer,
    summary           text,
    category_id       integer NOT NULL REFERENCES categories (id)
);

-- Relação N:N entre livro e autor
CREATE TABLE book_author (
    book_id   integer NOT NULL REFERENCES books (id),
    author_id integer NOT NULL REFERENCES authors (id),
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE book_copies (
     id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     book_id           integer NOT NULL REFERENCES books (id),
     accession_number  varchar(30) NOT NULL UNIQUE,
     physical_location varchar(100),
     status            dom_copy_status NOT NULL DEFAULT 'AVAILABLE'
);

-- Tabela fato: um exemplar participa de vários empréstimos ao longo do tempo
CREATE TABLE loans (
   id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   copy_id        integer NOT NULL REFERENCES book_copies (id),
   reader_id      integer NOT NULL REFERENCES users (id),
   librarian_id   integer NOT NULL REFERENCES users (id),
   loan_date      date    NOT NULL,
   due_date       date    NOT NULL,
   return_date    date,   -- null until the copy is returned
   renewal_count  integer NOT NULL DEFAULT 0,
   CONSTRAINT ck_loan_renewal_count CHECK (renewal_count >= 0),
   CONSTRAINT ck_loan_dates CHECK (due_date >= loan_date)
);

-- Um exemplar só pode ter um empréstimo ativo (sem devolução) por vez
CREATE UNIQUE INDEX uq_loan_active_copy
    ON loans (copy_id)
    WHERE return_date IS NULL;

-- ---------------------------------------------------------------
-- Views
-- ---------------------------------------------------------------
-- Status do empréstimo calculado a partir das datas, sem ser armazenado: evita que "ON_TIME" fique desatualizado quando a data prevista passa.
CREATE VIEW vw_loans AS
SELECT l.*,
       (CASE
            WHEN l.return_date IS NOT NULL THEN 'RETURNED'
            WHEN CURRENT_DATE > l.due_date THEN 'OVERDUE'
            ELSE 'ON_TIME'
           END)::varchar(20) AS status
FROM loans l;